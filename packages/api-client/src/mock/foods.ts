export interface MockCatalogFood extends SearchableFood {
  key: string;
  per100g: Food['per100g'];
  servings: { id: string; labelEs: string; labelEn: string; grams: number }[];
}

const id = (prefix: string, n: number) =>
  `00000000-0000-4000-${prefix}-${n.toString(16).padStart(12, '0')}`;

export const MOCK_CATALOG: MockCatalogFood[] = ROWS.map(
  (
    [key, nameEs, nameEn, synonymsEs, popularity, [kcal, proteinG, carbsG, fatG, fiberG], servings],
    i,
  ) => ({
    id: id('8000', i + 1),
    key,
    nameEs,
    nameEn,
    synonymsEs,
    popularity,
    per100g: { kcal, proteinG, carbsG, fatG, fiberG },
    servings: servings.map(([labelEs, labelEn, grams], j) => ({
      id: id('9000', (i + 1) * 16 + j),
      labelEs,
      labelEn,
      grams,
    })),
  }),
);

export const MOCK_SOURCE = 'ciqual-2025';

/** A catalog food in one language, as the API returns it. */
export function toMockFood(food: MockCatalogFood, locale: Locale): Food {
  return {
    id: food.id,
    key: food.key,
    name: locale === 'en' ? food.nameEn : food.nameEs,
    per100g: food.per100g,
    servings: food.servings.map((s) => ({
      id: s.id,
      label: locale === 'en' ? s.labelEn : s.labelEs,
      grams: s.grams,
    })),
    source: MOCK_SOURCE,
  };
}
